/**
 * Generates src/deployments.ts from packages/contracts/deployments/*.json.
 *
 *   node scripts/gen-deployments.mjs          write src/deployments.ts
 *   node scripts/gen-deployments.mjs --check  exit 1 if the committed file is stale
 *
 * Until a network's deployment file exists, every Polaris contract on it is the
 * zero address and `deployed` is false. The SDK refuses to send anything to a
 * zero address (see `assertDeployed` in src/chains.ts), so an undeployed preset
 * fails loudly at the call site instead of signing for a contract that isn't
 * there. There are never made-up addresses in this file.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sdkRoot = join(here, "..");
const deploymentsDir = join(sdkRoot, "..", "contracts", "deployments");
const outFile = join(sdkRoot, "src", "deployments.ts");

const ZERO = "0x0000000000000000000000000000000000000000";

/** Contract names as the deploy scripts write them → the SDK's field names. */
const NAMES = {
  PolarisPayments: "payments",
  PolarisLoanEngine: "loanEngine",
  ScoreManager: "scoreManager",
  CollateralVault: "collateralVault",
  PolarisCheckout: "checkout",
  PolarisSend: "send",
  MerchantRegistry: "merchantRegistry",
  PolarisCollector: "collector",
  BatchSettlement: "batchSettlement",
};

/** A deployment may bring its own dollar token (a MockAUSD while the AUSD faucet is dry). */
const STABLECOIN_NAMES = ["AUSD", "MockAUSD", "Stablecoin", "stablecoin"];

const NETWORKS = [
  { key: "monadTestnet", file: "monad-testnet.json", chainId: 10143 },
  { key: "monad", file: "monad.json", chainId: 143 },
];

function isAddress(value) {
  return typeof value === "string" && /^0x[0-9a-fA-F]{40}$/.test(value);
}

/**
 * A contract's address in a deployment record. packages/contracts' deploy
 * scripts write `{ address, blockNumber, txHash, ... }` per contract (the
 * Monad records); the older Sepolia records wrote the bare address string.
 * Both are read.
 */
export function addressOf(entry) {
  return entry !== null && typeof entry === "object" ? entry.address : entry;
}

export function load(network, dir = deploymentsDir) {
  const path = join(dir, network.file);
  const contracts = Object.fromEntries(Object.values(NAMES).map((field) => [field, ZERO]));
  if (!existsSync(path)) {
    return { network: network.key, chainId: network.chainId, source: null, deployedAt: null, stablecoin: null, contracts };
  }

  const json = JSON.parse(readFileSync(path, "utf8"));
  if (Number(json.chainId) !== network.chainId) {
    throw new Error(`${network.file}: chainId is ${json.chainId}, expected ${network.chainId}`);
  }
  const found = json.contracts ?? {};
  for (const [name, field] of Object.entries(NAMES)) {
    const address = addressOf(found[name]);
    if (address === undefined) continue;
    if (!isAddress(address)) throw new Error(`${network.file}: ${name} is not an address: ${address}`);
    contracts[field] = address;
  }
  let stablecoin = null;
  for (const name of STABLECOIN_NAMES) {
    const address = addressOf(found[name]);
    if (address !== undefined) {
      if (!isAddress(address)) throw new Error(`${network.file}: ${name} is not an address: ${JSON.stringify(found[name])}`);
      stablecoin = address;
      break;
    }
  }
  return {
    network: network.key,
    chainId: network.chainId,
    source: relative(join(sdkRoot, "..", ".."), path).replaceAll("\\", "/"),
    deployedAt: typeof json.deployedAt === "string" ? json.deployedAt : null,
    stablecoin,
    contracts,
  };
}

export function render(records) {
  const body = records
    .map((r) => {
      const contracts = Object.entries(r.contracts)
        .map(([field, address]) => `      ${field}: "${address}",`)
        .join("\n");
      return [
        `  ${r.network}: {`,
        `    chainId: ${r.chainId},`,
        `    source: ${JSON.stringify(r.source)},`,
        `    deployedAt: ${JSON.stringify(r.deployedAt)},`,
        `    stablecoin: ${r.stablecoin ? `"${r.stablecoin}"` : "null"},`,
        `    contracts: {`,
        contracts,
        `    },`,
        `  },`,
      ].join("\n");
    })
    .join("\n");

  return `/**
 * GENERATED by scripts/gen-deployments.mjs from packages/contracts/deployments.
 * Do not edit by hand: run \`pnpm --filter polarispay-sdk gen:deployments\`.
 *
 * A network with \`source: null\` has no deployment file yet. Its Polaris
 * contracts are the zero address, on purpose: the SDK refuses to use them
 * (assertDeployed in chains.ts) rather than sign for a contract that isn't
 * there.
 */

import type { Address, ContractName } from "./types.js";

export type DeploymentRecord = {
  chainId: number;
  /** The deployment file this was generated from, or null if there is none yet. */
  source: string | null;
  deployedAt: string | null;
  /** A dollar token the deployment brought (e.g. MockAUSD), or null to use Agora's AUSD. */
  stablecoin: Address | null;
  contracts: Record<ContractName, Address>;
};

export const DEPLOYMENTS: { monadTestnet: DeploymentRecord; monad: DeploymentRecord } = {
${body}
};
`;
}

export { NETWORKS };

function main() {
  const next = render(NETWORKS.map((n) => load(n)));
  if (process.argv.includes("--check")) {
    const current = existsSync(outFile) ? readFileSync(outFile, "utf8").replaceAll("\r\n", "\n") : "";
    if (current !== next) {
      console.error("src/deployments.ts is stale. Run: pnpm --filter polarispay-sdk gen:deployments");
      process.exit(1);
    }
    console.log("src/deployments.ts is up to date.");
  } else {
    writeFileSync(outFile, next);
    console.log(`Wrote ${relative(process.cwd(), outFile)}`);
  }
}

// Run only as a script: the tests import load() and render(). (Windows paths
// compare without case: a drive letter may arrive as f: or F:.)
const same = (a, b) => (process.platform === "win32" ? a.toLowerCase() === b.toLowerCase() : a === b);
if (process.argv[1] && same(resolve(process.argv[1]), fileURLToPath(import.meta.url))) main();
